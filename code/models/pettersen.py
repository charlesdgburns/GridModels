def pad_ratemaps_and_bins_np(maps, binx, biny):
    """
    maps: (n_neurons, n_xbins, n_ybins) float array
    binx, biny: 1D arrays of bin centers (len nx, ny)
    Returns: maps_sq (n, S, S), binx_S (S,), biny_S (S,)
    - Pads maps with NaNs, centered.
    - Extrapolates the shorter bin list on both ends to reach S.
    """
    assert maps.ndim == 3
    n, nx, ny = maps.shape
    S = max(nx, ny)
    out = np.full((n, S, S), np.nan, dtype=maps.dtype if np.issubdtype(maps.dtype, np.floating) else np.float32)

    # where to place the original data (center)
    x0 = (S - nx) // 2; x1 = x0 + nx
    y0 = (S - ny) // 2; y1 = y0 + ny
    out[:, x0:x1, y0:y1] = maps

    def _extrapolate(b, target_len):
        if len(b) == target_len: return b.copy()
        need = target_len - len(b)
        return np.concatenate([b, np.repeat([np.nan],need)])
    
    target_len = np.max([len(binx),len(biny)])
    binx_S = _extrapolate(np.asarray(binx), target_len)
    biny_S = _extrapolate(np.asarray(biny), target_len)
    return out, binx_S, biny_S