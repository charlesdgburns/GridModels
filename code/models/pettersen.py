## EFFICIENT DATALOADING ## 
class PositionDataset(Dataset):
    def __init__(self, n_steps=150000, 
                 real_or_riab = 'riab',
                 maze_name_or_open_field = 'open_field',
                 train_or_test = 'train'): 
        filepath = TRAJECTORIES_DIR/f'{real_or_riab}.{maze_name_or_open_field}.{train_or_test}.htsv'

        if n_steps != 150000 and real_or_riab == 'riab':
            print(f'Generating trajectory with {n_steps} steps taken.')
            box = riab.Environment(params = {'scale':options.environment_scale})
            rat = riab.Agent(box, params={"dt":options.framerate})
            for i in tqdm(range(n_steps)):
                rat.update() 
            self.positions = torch.tensor(rat.history['pos'], dtype=torch.float32).to(DEVICE)
        elif filepath.exists():
            print(f'Loading saved trajectory {real_or_riab}.{maze_name_or_open_field}.{train_or_test}.htsv')
            df = pd.read_csv(filepath, sep='\t')
            df.columns = pd.MultiIndex.from_tuples(
            [col.split('.') if '.' in col else (col,'') for col in df.columns])
            self.positions = torch.tensor(df.centroid_position.values,dtype=torch.float32).to(DEVICE)
        else:
            print('Sorry, file not found.')
          
    def __len__(self):
        return len(self.positions)

    def __getitem__(self, idx):
        return self.positions[idx]

  

## FEEDFORWARD MODEL ##
class PositionEncoder(nn.Module):
    def __init__(self,
                 positions_for_LUT,
                 distance_metric = options.distance_metric,
                 alpha = 0.8,
                 sigma = 0.6,
                 input_size=2,# input_size is 2D coordinates, output_size is n_g
                 hidden_1_size = 64,
                 hidden_2_size = 128,
                 output_size=256,): 
        super(PositionEncoder, self).__init__()
        self.layer = nn.Sequential(
            nn.Linear(input_size, hidden_1_size), # Example hidden layer size
            nn.ReLU(),
            nn.Linear(hidden_1_size,hidden_2_size),
            nn.ReLU(),
            nn.Linear(hidden_2_size, output_size),
            nn.ReLU() #here the authors take normReLU(x) = ReLU(x)/maximum(||ReLU(x)||,epsilon), epsilon =10-12; let's see if this is strictly necessary
        )
        self.alpha = alpha
        self.sigma = sigma
        self.mse = torch.nn.MSELoss()
        self.LUT = DistanceLUT(positions_for_LUT, 
                                distance_metric = distance_metric,
                                device = DEVICE)
        self.LUT_pdist = self.LUT.pairwise

    def initialise_weights(self):
        for name,param in self.named_parameters():
          if 'weight' in name:
                nn.init.kaiming_uniform_(param, nonlinearity='relu')

    def forward(self, x):
        out = self.layer(x)
        out = torch.nn.functional.normalize(out, p=2.0, dim=1, eps=1e-18, out=None) #apply normReLU()
        return out

    def compute_losses(self, inputs, outputs):
        pos_distances = self.LUT_pdist(inputs) #torch.pdist(inputs)
        g_distances = torch.pdist(outputs)
        distance_loss = self.alpha*torch.mean(torch.exp(-pos_distances**2/(2*(self.sigma**2)))*(pos_distances-g_distances)**2)
        capacity_loss = (1-self.alpha)*(torch.mean(-torch.sum(outputs, dim=1)))
        return distance_loss, capacity_loss

# -subfunctions- #

class DistanceLUT(nn.Module):
    """
    Nearest‑cell LUT distances.
    Assumes positions lie within [x0,x1] × [y0,y1].
    Returns only the condensed upper‑triangle distances.
    
    NOTE: returns distances in m/10, as for numerical reasons we want far distances to be above 1.
    """
    def __init__(self, pos, bin_size=0.03, 
                 distance_metric = 'euclidean',
                 device=DEVICE):
        '''Requires pos (n_postitions,2) torch tensor input.
        Generates a look-up table for distances between points'''
        super().__init__()
        self.pos = pos        
        self.bin_size = float(bin_size)
        self.distance_metric = distance_metric
        self.device = device

        pixel_maze, bin_mask, meta = mr.get_pixel_maze(self.pos.to(device='cpu').numpy(), 
                                                pixel_size = self.bin_size,
                                                allow_diagonal = True,
                                                return_bin_mask = True,
                                                return_meta = True)
        self.pixel_maze = pixel_maze
        self.bin_mask = bin_mask# for optional checks
        self.Hx, self.Hy = meta["shape"]
        self.x0, self.y0 = float(meta["x0"]), float(meta["y0"])
        self.bin_size = float(meta["pixel_size"])

        # keep edges as buffers on the device for bucketize
        x_edges = torch.tensor(meta["x_edges"], dtype=torch.float32, device = self.device)
        y_edges = torch.tensor(meta["y_edges"], dtype=torch.float32, device = self.device)
        self.register_buffer("x_edges", x_edges)
        self.register_buffer("y_edges", y_edges)
        
        D = self.compute_D(distance_metric = self.distance_metric).to(self.device)
        self.register_buffer('D',D)

    def compute_D(self, distance_metric = 'euclidean'):
        assert distance_metric in ['euclidean','geodesic']
          
        if distance_metric == 'euclidean':
            xs = torch.arange(self.x0 + self.bin_size/2,
                              self.x0 + self.Hx*self.bin_size,
                              self.bin_size, device=self.device)
            ys = torch.arange(self.y0 + self.bin_size/2,
                              self.y0 + self.Hy*self.bin_size,
                              self.bin_size, device=self.device)
            Xc, Yc = torch.meshgrid(xs, ys, indexing='ij')
            centers = torch.stack([Xc.reshape(-1), Yc.reshape(-1)], dim=-1)  # (M,2)

            with torch.no_grad():
                D = torch.cdist(centers, centers, p=2)*10  # (M,M) LUT //multiplication by 10 for numerical reasons.
          
        elif distance_metric == 'geodesic':
            Hx, Hy = self.Hx, self.Hy
            n_nodes = Hx * Hy
            D = np.full((n_nodes, n_nodes), np.nan, dtype=np.float32)
            # Weighted all-pairs (uses Dijkstra with 'weight')
            for (si, sj), dist_dict in nx.all_pairs_dijkstra_path_length(self.pixel_maze, weight='weight'):
                u = si * Hy + sj                      # row-major linearization
                for (ti, tj), d in dist_dict.items():
                    v = ti * Hy + tj
                    D[u, v] = d                       # d is already in METERS (s or sqrt(2)*s, accumulated)
            # no extra scaling by bin_size — it's already encoded in edge weights
            D = torch.from_numpy(D).to(self.device)*10 #multiply by 10 for numerical reasons
        return D
    
    @torch.no_grad()
    def _to_idx(self, P):
        eps = 1e-9
        x = P[:, 0].clamp(self.x_edges[0], self.x_edges[-1] - eps)
        y = P[:, 1].clamp(self.y_edges[0], self.y_edges[-1] - eps)
        ix = torch.bucketize(x, self.x_edges, right=False) - 1
        iy = torch.bucketize(y, self.y_edges, right=False) - 1
        ix = ix.clamp(0, self.Hx - 1)
        iy = iy.clamp(0, self.Hy - 1)
        return ix * self.Hy + iy

    def pairwise(self, P):
        """
        P: (B,2) positions -> (B*(B-1)//2,) distances (condensed upper triangle).
        """
        idx = self._to_idx(P) # (B,)
        d_full = self.D.index_select(0, idx).index_select(1, idx)  # (B,B)
        iu = torch.triu_indices(d_full.size(0), d_full.size(1), offset=1, device=P.device)
        return d_full[iu[0], iu[1]]



## TRAINING LOOP ##
def train_model(options, plot_losses = True):
        
    # create dataset and dataloader
    dataset = PositionDataset(n_steps=options.trajectory_steps,
                              real_or_riab = options.real_or_riab,
                              maze_name_or_open_field = options.maze_name_or_open_field)
    dataloader = DataLoader(dataset, batch_size=options.batch_size, shuffle=True)
    # instantiate model
    model = PositionEncoder(positions_for_LUT = dataset.positions, 
                            distance_metric = options.distance_metric,
                            alpha=options.alpha, sigma=options.sigma,
                            hidden_1_size = options.first_hidden_size,
                            hidden_2_size = options.second_hidden_size,
                            output_size = options.n_grid_cells).to(options.device)
    model.initialise_weights()
    assert options.optimizer in ['Adam','AdamW']
    if options.optimizer == 'Adam':
        optimizer = torch.optim.Adam(model.parameters(), lr=options.learning_rate)
    elif options.optimizer == 'AdamW':
        optimizer = torch.optim.AdamW(model.parameters(), lr=options.learning_rate,
                                      weight_decay=0.0, amsgrad=True ) #prevent ReLU implicit  (https://arxiv.org/abs/1812.08119)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(optimizer, patience = 1000, factor = 0.5)
    losses = {'train':{'distance_losses':[],'capacity_losses':[]}}
    n_epochs = int( options.train_steps / (len(dataset.positions) / options.batch_size))
    
    for i in tqdm(range(n_epochs)): #nepochs
        for positions in dataloader:
            out = model(positions)
            distance_loss, capacity_loss = model.compute_losses(positions, out)
            loss = distance_loss + capacity_loss
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()
            #append losses for plotting
            losses['train']['distance_losses'].append(distance_loss.item())
            losses['train']['capacity_losses'].append(capacity_loss.item())
            #scheduler.step(loss.item())
    if plot_losses:
        fig, ax = plt.subplots(1,2, figsize = (10,3))
        ax[0].set_title('encoding loss')
        ax[0].loglog(losses['train']['distance_losses'])
        ax[1].set_title('capacity loss')
        ax[1].plot(losses['train']['capacity_losses'])
        ax[1].set_xscale('log')
    #evaluate gridness    
    gridcell_metrics_df = get_gridcell_metrics_df(model)
    return model, losses, gridcell_metrics_df


## INSPECT MODEL ##
def get_gridcell_metrics_df(model):
    '''Incredibly optimised code to just get gridscores'''
    from GridModels.code.measures import spatial
    from GridModels.code.measures import grid_scorer
    print('Computing Gridscores!')
    pos = torch.tensor([x for x in nx.get_node_attributes(model.LUT.pixel_maze,'position').values()],
                       device = model.LUT.device, dtype = torch.float32)
    with torch.no_grad():
        hidden_activations = model(pos)
    ratemaps, binx, biny = spatial.get_2D_ratemaps(hidden_activations.cpu().numpy(),
                                                    pos.cpu().numpy())
    ratemaps, binx, biny = pad_ratemaps_and_bins_np(ratemaps, binx, biny) #see utility function at bottom of script

    gridcell_metrics = grid_scorer.get_grid_scores(ratemaps,binx,biny, return_metrics=True)
    gridcell_metrics_df = pd.DataFrame(gridcell_metrics)
    return gridcell_metrics_df

## LOAD AND SAVE FUNCTIONS ##

def get_model_and_data(options):
    
    if (Path(options.save_dir)/generate_model_id(options)).exists():
        print('Loading existing model and data!')
        model, losses, gridcell_metrics_df = load_model(options)
    else:
        model, losses, gridcell_metrics_df = train_model(options)
        save_model_run(options,model,losses, gridcell_metrics_df)
    return model, losses, gridcell_metrics_df

def save_model_run(options, model, losses, gridcell_metrics_df):
    # generate a unique model ID based on the options
    model_id = generate_model_id(options)
    print(f"Saving model and data with ID: {model_id}")
    files_dir = Path(options.save_dir)/model_id
    Path(files_dir).mkdir(parents=True, exist_ok=True)  # Create directory if not already existing
    torch.save(model.to(device='cpu').state_dict(), files_dir/f"model.pt")

    options_dict = options.__dict__.copy()  # Copy options to avoid modifying the original
    options_dict = {k:str(v) for k,v in options_dict.items()}  # Convert all values to strings
    with open(files_dir/'options.json','w') as f:
        json.dump(options_dict, f, indent=4)
    
    losses_dict = {f'{k}.{key}':v[key] for k, v in losses.items() for key in v.keys()}
    losses_df = pd.DataFrame(losses_dict)

    losses_df.to_csv(files_dir/'losses.htsv', sep = '\t', index=False)
    try:
        gridcell_metrics_df.to_csv(files_dir/'gridcell_metrics.htsv', sep = '\t', index=False)
    except:
        print('failed to generate grid cell metrics')
    return 


def load_model(options):
    """Load a model from the specified directory.
    Parameters:
        options (Options): Options object containing the save directory and model ID.
    Returns:
        model (vel2pc_RNN): The loaded model.
    """
    model_id = generate_model_id(options)
    files_dir = Path(options.save_dir)/model_id
    # create dataset and dataloader
    dataset = PositionDataset(n_steps=options.trajectory_steps,
                              real_or_riab = options.real_or_riab,
                              maze_name_or_open_field = options.maze_name_or_open_field)
    # instantiate model
    model = PositionEncoder(positions_for_LUT = dataset.positions, 
                            distance_metric = options.distance_metric,
                            alpha=options.alpha, sigma=options.sigma,
                            hidden_1_size = options.first_hidden_size,
                            hidden_2_size = options.second_hidden_size,
                            output_size = options.n_grid_cells).to(options.device)
    model.load_state_dict(torch.load(files_dir/"model.pt", 
                                     weights_only=True))
    try:
        losses = pd.read_csv(files_dir/'losses.htsv', sep = '\t')
        losses.columns = pd.MultiIndex.from_tuples(
            [tuple(col.split('.')) if '.' in col else (col,"") for col in losses.columns ]
        )
    except Exception as e:
        print(f'Failed to load losses: {e}')
        losses = None
    try:
        gridcell_metrics = pd.read_csv(files_dir/f'gridcell_metrics.htsv', sep = '\t')
    except Exception as e:
        print(f'failed to load dataset: {e}')
        gridcell_metrics = None
    return model, losses, gridcell_metrics,  


